"""Figures of the paper (Figure 1 only if REGENERATE_FIG1 is set) (vector PDF), drawn from the data files in ../data.

  Figure 1  fig1_mehler_heine.pdf         F_n(x), n = 50, 200, 800, and F(x) on [-4, 2]      (data/fig1_*.csv)
  Figure 2  fig2_exceptional_zero.pdf     n(x_{n,alpha}-alpha) and e_n, 40 <= n <= 1600       (data/zeros_exceptional.csv)
  Figure 3  fig3_relative_asymptotics.pdf n S_n(x)/P_n(x), n = 50, 200, 800, on [-5, -0.25]   (data/fig3_*.csv)

Colours: the approximants use one blue hue from light to dark (increasing n) with distinct dash patterns; the limit
is a solid vermillion line.  The two families in Figure 2 use the Okabe-Ito blue/vermillion pair with different
markers.  Text is typeset by matplotlib's mathtext with the Computer Modern fonts."""
import csv, os, shutil
import matplotlib
matplotlib.use('pdf')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
OUT = os.path.join(HERE, '..', 'figures')
os.makedirs(OUT, exist_ok=True)

USETEX = False   # matplotlib's usetex needs the cm-super fonts; mathtext with Computer Modern is used instead
plt.rcParams.update({
    'text.usetex': USETEX, 'font.family': 'serif', 'font.serif': ['cmr10'], 'axes.formatter.use_mathtext': True, 'axes.unicode_minus': True,
    'mathtext.fontset': 'cm', 'font.size': 9, 'axes.labelsize': 9, 'axes.titlesize': 9, 'legend.fontsize': 8.5,
    'xtick.labelsize': 8, 'ytick.labelsize': 8, 'axes.linewidth': 0.6, 'xtick.major.width': 0.6,
    'ytick.major.width': 0.6, 'xtick.direction': 'out', 'ytick.direction': 'out', 'pdf.fonttype': 42,
    'text.latex.preamble': r'\usepackage{amsfonts}', 'axes.spines.top': False, 'axes.spines.right': False, 'legend.frameon': False,
})
BLUES = {50: '#5E97CC', 200: '#225C9C', 800: '#0A2A55'}
DASH = {50: (0, (1.2, 1.6)), 200: (0, (4.5, 2.0)), 800: (0, (7.0, 2.0, 1.5, 2.0))}
LIMIT = '#D55E00'
FAM = {'Charlier': dict(color='#0072B2', marker='o'), 'Meixner': dict(color='#D55E00', marker='s')}
ALPHA = -2.5
W = 6.3          # inches = \textwidth (16 cm)


def read(name):
    return list(csv.DictReader(open(os.path.join(DATA, name))))


def draw(ax, rows, lw=1.25, ms=5.5):
    x = [float(r['x']) for r in rows]
    ax.axhline(0, color='0.6', lw=0.5, zorder=0)
    for n in (50, 200, 800):
        ax.plot(x, [float(r[f'n{n}']) for r in rows], color=BLUES[n], ls=DASH[n], lw=lw, zorder=2)
    ax.plot(x, [float(r['limit']) for r in rows], color=LIMIT, lw=lw + 0.35, zorder=3)
    ax.plot([ALPHA], [0], 'o', ms=ms, mfc='white', mec='black', mew=0.9, zorder=4)
    return x


def profile_panel(ax, rows, title, ylabel):
    x = draw(ax, rows)
    ax.set_title(title, loc='left')
    ax.set_xlabel('$x$')
    ax.set_ylabel(ylabel)
    ax.set_xlim(x[0], x[-1])


def zoom_inset(ax, rows, bounds, xr, yr):
    """Magnified view of the neighbourhood of the mass point, placed in an empty region of the panel."""
    ins = ax.inset_axes(bounds)
    sub = [r for r in rows if xr[0] - 0.05 <= float(r['x']) <= xr[1] + 0.05]
    draw(ins, sub, lw=1.0, ms=4.5)
    ins.set_xlim(*xr)
    ins.set_ylim(*yr)
    ins.tick_params(labelsize=6.5, length=2, pad=1.5)
    for sp in ('top', 'right'):
        ins.spines[sp].set_visible(True)
    for sp in ins.spines.values():
        sp.set_linewidth(0.5); sp.set_color('0.35')
    ins.patch.set_facecolor('white')
    ins.set_title(r'near $\alpha$', fontsize=7, pad=2)
    return ins


def legend_handles(limlabel):
    h = [Line2D([], [], color=LIMIT, lw=1.6, label=limlabel)]
    h += [Line2D([], [], color=BLUES[n], ls=DASH[n], lw=1.25, label=f'$n={n}$') for n in (50, 200, 800)]
    h += [Line2D([], [], ls='', marker='o', ms=5.5, mfc='white', mec='black', mew=0.9, label=r'$\alpha=-5/2$')]
    return h


# ---------------- Figure 1 -------------------------------------------------------------------------------
# Figure 1 (fig1_mehler_heine.pdf) has been approved by the authors and is NOT regenerated by default;
# set REGENERATE_FIG1 = True only to reproduce it from data/fig1_*.csv.
REGENERATE_FIG1 = False
if REGENERATE_FIG1:
    fig, axs = plt.subplots(1, 2, figsize=(W, 3.1))
    rc, rm = read('fig1_charlier.csv'), read('fig1_meixner.csv')
    profile_panel(axs[0], rc, r'(a) Charlier, $\mu=5$', '$F_n(x)$')
    profile_panel(axs[1], rm, r'(b) Meixner, $\gamma=2$, $\mu=1/2$', '$F_n(x)$')
    axs[0].set_ylim(-560, 280)
    zoom_inset(axs[0], rc, (0.11, 0.10, 0.30, 0.24), (-3.7, -1.8), (-90, 70))
    zoom_inset(axs[1], rm, (0.10, 0.12, 0.40, 0.40), (-3.7, -1.8), (-0.55, 0.4))
    for ax in axs:
        ax.set_xticks(range(-4, 3))
    fig.legend(handles=legend_handles('limit $F$'), loc='upper center', ncol=5, bbox_to_anchor=(0.5, 1.0), handlelength=2.6,
               columnspacing=1.6)
    fig.tight_layout(rect=(0, 0, 1, 0.91), w_pad=2.0)
    fig.savefig(os.path.join(OUT, 'fig1_mehler_heine.pdf'))
    plt.close(fig)

# ---------------- Figure 2 -------------------------------------------------------------------------------
rows = [r for r in read('zeros_exceptional.csv') if r['experiment'] == 'main' and int(r['n']) >= 40]
fig, axs = plt.subplots(1, 2, figsize=(W, 2.9))
for fam, st in FAM.items():
    R = [r for r in rows if r['family'] == fam]
    n = [int(r['n']) for r in R]
    a1 = float(R[0]['a1'])
    axs[0].hlines(a1, 33, 1900, color=st['color'], ls=(0, (4, 2.5)), lw=0.9, zorder=1)
    axs[0].plot(n, [float(r['n_times_d']) for r in R], ls='', marker=st['marker'], ms=4.2, mfc=st['color'],
                mec='white', mew=0.5, color=st['color'], zorder=3, label=fam)
    axs[0].text(2050, a1, f'$a_1={int(a1)}$', va='center', ha='left', fontsize=8, color='0.15')
    axs[1].loglog(n, [float(r['e_n']) for r in R], ls='', marker=st['marker'], ms=4.2, mfc=st['color'], mec='white',
                  mew=0.5, color=st['color'], zorder=3, label=fam)
axs[0].set_xscale('log')
axs[0].set_xlabel('$n$')
axs[0].set_ylabel(r'$n\,(x_{n,\alpha}-\alpha)$')
axs[0].set_title(r'(a) $n\,(x_{n,\alpha}-\alpha)\to a_1$', loc='left')
axs[0].set_xlim(33, 4200)
axs[0].set_ylim(-66, -8)
ref_n = [40, 1600]
ref0 = 5.0 * 1700 / 40 ** 2
axs[1].loglog(ref_n, [ref0 * (40 / m) ** 2 for m in ref_n], color='0.35', ls=(0, (1, 1.5)), lw=1.0, zorder=1)
axs[1].text(330, ref0 * (40 / 330) ** 2 * 1.9, 'slope $-2$', fontsize=8, color='0.25', rotation=-27)
axs[1].set_xlabel('$n$')
axs[1].set_ylabel(r'$e_n=|x_{n,\alpha}-\alpha-a_1/n|$')
axs[1].set_title(r'(b) remainder $e_n$', loc='left')
for ax in axs:
    ax.set_xticks([50, 100, 200, 400, 800, 1600])
    ax.set_xticklabels(['50', '100', '200', '400', '800', '1600'])
    ax.minorticks_off() if ax is axs[0] else None
handles = [Line2D([], [], ls='', marker=FAM[f]['marker'], ms=4.5, color=FAM[f]['color'], mec='white', mew=0.5,
                  label=f) for f in FAM]
fig.legend(handles=handles, loc='upper center', ncol=2, bbox_to_anchor=(0.5, 1.0))
fig.tight_layout(rect=(0, 0, 1, 0.91), w_pad=2.0)
fig.savefig(os.path.join(OUT, 'fig2_exceptional_zero.pdf'))
plt.close(fig)

# ---------------- Figure 3 -------------------------------------------------------------------------------
fig, axs = plt.subplots(1, 2, figsize=(W, 2.9))
profile_panel(axs[0], read('fig3_charlier.csv'), r'(a) Charlier, $\mu=5$', r'$n\,\mathbb{S}_n(x)/P_n(x)$')
profile_panel(axs[1], read('fig3_meixner.csv'), r'(b) Meixner, $\gamma=2$, $\mu=1/2$', r'$n\,\mathbb{S}_n(x)/P_n(x)$')
for ax in axs:
    ax.set_xticks([-5, -4, -3, -2, -1])
fig.legend(handles=legend_handles(r'limit $-(x-\alpha)/c_\mu$'), loc='upper center', ncol=5, bbox_to_anchor=(0.5, 1.0),
           handlelength=2.6, columnspacing=1.6)
fig.tight_layout(rect=(0, 0, 1, 0.91), w_pad=2.0)
fig.savefig(os.path.join(OUT, 'fig3_relative_asymptotics.pdf'))
plt.close(fig)
print('figures written to', os.path.abspath(OUT), '(usetex=%s)' % USETEX)
