from fractions import Fraction as Fr
from math import comb, factorial
import sys

ok_all = True


def report(label, ok):
    global ok_all
    ok_all &= ok
    print(f'{label}: {"OK" if ok else "FAIL"}', flush=True)


def coeffs(fam, mu, g):
    if fam == 'C':
        return (lambda n: n + mu), (lambda n: n * mu)
    return (lambda n: (n * (1 + mu) + mu * g) / (1 - mu)), (lambda n: n * mu * (n - 1 + g) / (mu - 1) ** 2)


def P_rec(fam, mu, g, N, x):
    a, b = coeffs(fam, mu, g)
    P = [Fr(1), x - a(0)]
    for n in range(1, N):
        P.append((x - a(n)) * P[n] - b(n) * P[n - 1])
    return P[:N + 1]


def rf(a, k):
    r = Fr(1)
    for i in range(k):
        r *= a + i
    return r


def P_hyp(fam, mu, g, n, x):
    if fam == 'C':
        s = sum(rf(-n, i) * rf(-x, i) / factorial(i) * (Fr(-1) / mu) ** i for i in range(n + 1))
        return (-mu) ** n * s
    z = 1 - 1 / mu
    s = sum(rf(-n, i) * rf(-x, i) / (rf(g, i) * factorial(i)) * z ** i for i in range(n + 1))
    return rf(g, n) * (mu / (mu - 1)) ** n * s


FAMS = [('C', Fr(5), None), ('C', Fr(1, 3), None), ('M', Fr(1, 2), Fr(2)), ('M', Fr(1, 3), Fr(7, 2)), ('M', Fr(2, 5), Fr(1))]
XS = [Fr(-5, 2), Fr(-1, 2), Fr(0), Fr(3), Fr(7, 3), Fr(-17, 4)]

# (A, B)
for fam, mu, g in FAMS:
    good = all(P_rec(fam, mu, g, 25, x)[n] == P_hyp(fam, mu, g, n, x) for x in XS for n in range(26))
    report(f'(A/B) recurrence = hypergeometric representation, {fam} mu={mu} gamma={g}, n<=25', good)

# (C)
for fam, mu, g in FAMS:
    good = True
    for k in range(0, 11):
        gk = None if g is None else g + k
        for x in XS:
            Px = [P_rec(fam, mu, g, 25, x + i) for i in range(k + 1)]
            Pk = P_rec(fam, mu, gk, 25, x)
            for n in range(k, 26):
                lhs = sum((-1) ** (k - i) * comb(k, i) * Px[i][n] for i in range(k + 1))
                ff = 1
                for r in range(k):
                    ff *= n - r
                good &= lhs == ff * Pk[n - k]
    report(f'(C) forward shift Delta^k P_n = [n]_k P^[k]_(n-k), {fam} mu={mu} gamma={g}, k<=10, n<=25', good)


