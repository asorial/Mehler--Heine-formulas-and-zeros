def padd(p, q):
    n = max(len(p), len(q))
    return [(p[i] if i < len(p) else 0) + (q[i] if i < len(q) else 0) for i in range(n)]


def pscale(p, c):
    return [c * v for v in p]


def pmul(p, q):
    r = [Fr(0)] * (len(p) + len(q) - 1)
    for i, u in enumerate(p):
        for k, v in enumerate(q):
            r[i + k] += u * v
    return r


def peval(p, t):
    s = Fr(0)
    for c in reversed(p):
        s = s * t + c
    return s


def trim(p):
    while len(p) > 1 and p[-1] == 0:
        p = p[:-1]
    return p


_st = {}


def stirling2(m, k):
    if (m, k) in _st:
        return _st[m, k]
    if m == k:
        r = 1
    elif k == 0 or k > m:
        r = 0
    else:
        r = k * stirling2(m - 1, k) + stirling2(m - 1, k - 1)
    _st[m, k] = r
    return r


def run(fam, mu, g, j, al, lam, N):
    a, b = coeffs(fam, mu, g)
    mom = (lambda k: mu ** k) if fam == 'C' else (lambda k: rf(g, k) * (mu / (1 - mu)) ** k * (1 - mu) ** (-g))
    mono = [sum(stirling2(m, k) * mom(k) for k in range(m + 1)) for m in range(2 * N + 2)]   # sum_x x^m rho(x)

    def bip(p, q):
        return sum(c * mono[m] for m, c in enumerate(pmul(p, q)))

    Dj = lambda p: sum((-1) ** (j - i) * comb(j, i) * peval(p, al + i) for i in range(j + 1))
    ip = lambda p, q: bip(p, q) + lam * Dj(p) * Dj(q)
    P = [[Fr(1)], [-a(0), Fr(1)]]
    for n in range(1, N):
        P.append(trim(padd(pmul([-a(n), Fr(1)], P[n]), pscale(P[n - 1], -b(n)))))
    nrm = [bip(P[k], P[k]) for k in range(N + 1)]
    D = [Dj(P[k]) for k in range(N + 1)]
    G = []
    for n in range(N + 1):
        xn = [Fr(0)] * n + [Fr(1)]
        v = xn
        for gk in G:
            v = padd(v, pscale(gk, -ip(xn, gk) / ip(gk, gk)))
        G.append(trim(v))
    good = True
    for n in range(1, N + 1):
        K0j = [Fr(0)]
        for k in range(n):
            K0j = padd(K0j, pscale(P[k], D[k] / nrm[k]))
        delta = 1 + lam * sum(D[k] ** 2 / nrm[k] for k in range(n))
        S = trim(padd(P[n], pscale(K0j, -lam * D[n] / delta)))
        good &= all(ip(S, [Fr(0)] * k + [Fr(1)]) == 0 for k in range(n))
        good &= trim(padd(S, pscale(G[n], -1))) == [0]
        if n > j:
            rhs = P[n]
            for k in range(j, n):
                rhs = padd(rhs, pscale(padd(P[n], pscale(P[k], -D[n] / D[k])), lam * D[k] ** 2 / nrm[k]))
            good &= trim(padd(pscale(S, delta), pscale(rhs, -1))) == [0]
    report(f'(D) connection formula = Gram-Schmidt, orthogonality, identity of Lemma 3.5: {fam} mu={mu} gamma={g} '
           f'j={j} alpha={al} lambda={lam}, n=1..{N}', good)


